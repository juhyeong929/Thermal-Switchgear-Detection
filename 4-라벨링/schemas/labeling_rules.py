def status_of(class_name):
    """이 클래스를 어떻게 다뤄야 하는가."""
    if class_name in EXCLUDED:
        return "제외 — 박스를 그리지 않는다"
    if class_name in CAUTIONED:
        return f"주의 — 식별 가능할 때만 라벨, 판별 불가면 {UNJUDGEABLE_MEANS}"
    return "가공 — 항상 라벨"


